#!/usr/bin/env python3
"""Evaluate the 72B reader on the 1,600-question confirmation population.

Reads the new base and joint posteriors, applies the frozen weight and the
development-selected confidence gate, and reports paired statistics against the
72B no-retrieval baseline and against unconditional reading.

Writes results/e9_72b_eval.json and results/e9_72b.tex (macros for the paper).

Usage
-----
    python -P code/eval_72b_e9.py
"""
from __future__ import annotations

import json
from math import comb
from pathlib import Path

import numpy as np

SEED = 20261025
DRAWS = 10000
ALPHA = 0.45
F2_TAU = 0.45  # selected on the 72B development population

HERE = Path(__file__).resolve()
REV = HERE.parents[1]
ROOT = HERE.parents[3]
NEW = REV / "results" / "new_reads"
V47 = ROOT / "new" / "v47_results"
OUT = REV / "results"


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]


def norm(p):
    p = np.clip(np.asarray(p, float), 1e-12, None)
    return p / p.sum(-1, keepdims=True)


def loglin(p0, pe, a):
    return norm(np.exp((1 - a) * np.log(norm(p0)) + a * np.log(norm(pe))))


def mcnemar(a, b):
    x = int((a & ~b).sum())
    y = int((~a & b).sum())
    n = x + y
    if n == 0:
        return 1.0, 0, 0
    k = min(x, y)
    return float(min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)), x, y


def boot(a, b, cl, draws=DRAWS, seed=SEED):
    rng = np.random.default_rng(seed)
    cl = np.asarray(cl)
    u = sorted(set(cl.tolist()))
    idx = {c: np.flatnonzero(cl == c) for c in u}
    n = len(u)
    d = np.empty(draws)
    for i in range(draws):
        s = rng.integers(0, n, n)
        ii = np.concatenate([idx[u[j]] for j in s])
        d[i] = a[ii].mean() - b[ii].mean()
    return [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]


def counts(pred, gold, bp):
    ok = pred == gold
    bo = bp == gold
    return float(ok.mean()), int(np.sum(~bo & ok)), int(np.sum(bo & ~ok)), ok


def pct(x):
    return f"{x*100:.2f}"


def ci(c):
    return f"[{c[0]*100:+.2f},{c[1]*100:+.2f}]"


def main():
    gold = {r["question_id"]: int(r["gold_index"])
            for r in jl(V47 / "e9_large_population" / "e9_predictions.jsonl")}
    base = {r["question_id"]: r for r in jl(NEW / "base72_e9.jsonl")}
    joint = {r["question_id"]: r for r in jl(NEW / "joint72_e9.jsonl")}
    qs = [q for q in gold if q in base and q in joint]
    g = np.array([gold[q] for q in qs])
    p0 = norm(np.array([base[q]["probabilities"] for q in qs]))
    pe = norm(np.array([joint[q]["probabilities"] for q in qs]))
    ents = [str(base[q]["entity_id"]) for q in qs]
    bp = p0.argmax(1)
    bo = bp == g

    pool = loglin(p0, pe, ALPHA)
    pred_pool = pool.argmax(1)
    keep = (pred_pool != bp) & (pool.max(1) < F2_TAU)
    pred_gate = pred_pool.copy()
    pred_gate[keep] = bp[keep]

    rep = {"n": len(qs), "n_entities": len(set(ents)),
           "norag": {"acc": float(bo.mean()), "n_correct": int(bo.sum())}}
    acc_e, c_e, h_e, ok_e = counts(pe.argmax(1), g, bp)
    rep["evidence_only"] = {"acc": acc_e, "corr": c_e, "harm": h_e}
    for tag, pred in [("cea_frozen", pred_pool), ("cea_gate", pred_gate)]:
        acc, c, h, ok = counts(pred, g, bp)
        rep[tag] = {"acc": acc, "corr": c, "harm": h,
                    "ci_vs_norag": boot(ok, bo, ents),
                    "mcnemar_vs_norag": mcnemar(ok, bo),
                    "ci_vs_evidence": boot(ok, ok_e, ents),
                    "mcnemar_vs_evidence": mcnemar(ok, ok_e)}
    accp, cp, hp, okp = counts(pred_pool, g, bp)
    accg, cg, hg, okg = counts(pred_gate, g, bp)
    rep["cea_gate"]["ci_vs_frozen"] = boot(okg, okp, ents)
    rep["cea_gate"]["mcnemar_vs_frozen"] = mcnemar(okg, okp)
    rep["deltas"] = {"frozen_minus_norag": accp - float(bo.mean()),
                     "frozen_minus_evidence": accp - acc_e,
                     "gate_minus_norag": accg - float(bo.mean())}

    json.dump(rep, open(OUT / "e9_72b_eval.json", "w", encoding="utf-8"),
              indent=2, ensure_ascii=False)

    L = ["%% Generated by code/eval_72b_e9.py from the 72B confirmation reads.",
         f"\\newcommand{{\\vRtwoN}}{{{len(qs)}}}",
         f"\\newcommand{{\\vRtwoNoRAG}}{{{pct(bo.mean())}}}",
         f"\\newcommand{{\\vRtwoEvAcc}}{{{pct(acc_e)}}}",
         f"\\newcommand{{\\vRtwoEvCorr}}{{{c_e}}}",
         f"\\newcommand{{\\vRtwoEvHarm}}{{{h_e}}}",
         f"\\newcommand{{\\vRtwoAcc}}{{{pct(accp)}}}",
         f"\\newcommand{{\\vRtwoCorr}}{{{cp}}}",
         f"\\newcommand{{\\vRtwoHarm}}{{{hp}}}",
         f"\\newcommand{{\\vRtwoCI}}{{{ci(rep['cea_frozen']['ci_vs_norag'])}}}",
         f"\\newcommand{{\\vRtwoP}}{{{rep['cea_frozen']['mcnemar_vs_norag'][0]:.2f}}}",
         f"\\newcommand{{\\vRtwoEvCI}}{{{ci(rep['cea_frozen']['ci_vs_evidence'])}}}",
         f"\\newcommand{{\\vRtwoEvP}}{{{rep['cea_frozen']['mcnemar_vs_evidence'][0]:.3f}}}",
         f"\\newcommand{{\\vRtwoGateAcc}}{{{pct(accg)}}}",
         f"\\newcommand{{\\vRtwoGateCorr}}{{{cg}}}",
         f"\\newcommand{{\\vRtwoGateHarm}}{{{hg}}}",
         f"\\newcommand{{\\vRtwoGateCI}}{{{ci(rep['cea_gate']['ci_vs_frozen'])}}}"]
    (OUT / "e9_72b.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(json.dumps(rep, indent=2))


if __name__ == "__main__":
    main()
